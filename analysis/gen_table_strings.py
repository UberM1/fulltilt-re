#!/usr/bin/env python3
"""Generate the engine's per-table RT_STRING tables.

    python3 analysis/gen_table_strings.py > reference/SpaceCadetPinball/table_strings.cpp

Why generated and embedded rather than read at runtime: the strings live in
DRAGON.EXE and PIRATES.EXE, and the port never opens those -- it stages only the
.DAT, which carries no RT_STRING resource at all. So "read it from the game data"
is not an option without shipping the executables, which this repo deliberately
does not. Embedding also matches what the port already does for Space Cadet,
whose strings are compiled into translations.cpp from pinball.exe's resources.

The input is analysis/<table>-strings.txt, produced by analysis/dump_strings.py
straight from the executables, one id per line with embedded newlines
backslash-escaped. The escaping matters: these strings are routinely
"<label>\\n%ld" (3007 is "Fire Ridge\\n%ld"), and the newline is a line break the
text box renders, so it has to survive into the C literal.
"""

import sys
from pathlib import Path

ANALYSIS = Path(__file__).parent
TABLES = [("dragon", "dragon_rc_strings"), ("pirates", "pirates_rc_strings")]


def read(table):
    out = {}
    for line in (ANALYSIS / f"{table}-strings.txt").read_text().splitlines():
        if not line.strip():
            continue
        ident, _, text = line.partition("\t")
        # The dump is unicode_escape'd; undo it so the real newlines come back.
        out[int(ident)] = text.encode("ascii").decode("unicode_escape")
    return out


def c_literal(s):
    body = (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{body}"'


def main():
    w = sys.stdout.write
    w("// GENERATED by analysis/gen_table_strings.py -- do not edit by hand.\n")
    w("//\n")
    w("// Each Full Tilt bonus table carries its own RT_STRING resources, and its rules\n")
    w("// name messages by those ids (Dragon's Keep 3001..3076, Skulduggery likewise).\n")
    w("// The port's shared Msg enum is Space Cadet's table only, so without these every\n")
    w("// bonus-table message resolved to translations.cpp's \"!Missing MsgId!\" placeholder\n")
    w("// and that is what the playfield displayed.\n")
    w("//\n")
    w("// Sorted by id; FindRcString binary-searches.\n")
    w('#include "pch.h"\n')
    w('#include "table_rules.h"\n')
    for table, symbol in TABLES:
        strings = read(table)
        # `extern` on the definition too: a namespace-scope `const` has internal
        # linkage in C++, and table_rules.cpp has to see these.
        w(f"\nextern const RcString {symbol}[];\n")
        w(f"const RcString {symbol}[] =\n{{\n")
        for ident in sorted(strings):
            w(f"\t{{{ident}, {c_literal(strings[ident])}}},\n")
        w("};\n")
        w(f"extern const size_t {symbol}_count;\n")
        w(f"const size_t {symbol}_count = {len(strings)};\n")


if __name__ == "__main__":
    main()
