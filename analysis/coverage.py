#!/usr/bin/env python3
"""Report how much of each table's rules have actually been ported.

"Percent done" is ambiguous here, so this reports the three measures that mean
different things and tends to get conflated:

  decompiled   -- how much of the binary has readable pseudocode. Near-total, and
                  not the bottleneck.
  classified   -- how many handlers have a named Space Cadet equivalent to work
                  from. Triage, not understanding.
  implemented  -- how many handlers have a real C++ body in src/. This is the one
                  that answers "how much of the port is done", and it is always
                  the smallest.

A handler counts as implemented when its original address appears in a src/ file,
which is reliable because every reimplementation carries its address in a comment
by convention. Bytes are counted too: handlers vary by an order of magnitude in
size, so 50% of handlers is not 50% of the work.

"Handlers" above means the functions bound in score_components[] -- the seeds file,
64 for Dragon's Keep and 69 for Skulduggery -- and nothing else. That is NOT the
whole rules region. The table-level control handler (DRAGON.EXE 0x424260,
PIRATES.EXE 0x4230c0) and the key handler (0x4282c0 / 0x42a830) are bound in
neither array and reached only from engine code, so for a long time this script
said 100% while both were missing and tilting either table crashed.

So a second measure follows, the rules-region census:

  region       -- every function Ghidra found between the first and last address
                  with no CADET.EXE counterpart: DRAGON.EXE 0x422a80..0x42c290,
                  PIRATES.EXE 0x422a80..0x42daa0. The bounds come from comparing
                  every function against CADET.EXE (normalised instruction hashes,
                  then similarity); the bytes in between that are outside any
                  Ghidra body were checked and are padding, jump tables or
                  non-contiguous parts of neighbouring functions, so the Ghidra
                  list is the whole list.
  in src/      -- the function's address is cited in that table's own src/ files.
                  A citation is a comment, so this is "has a counterpart", not "is
                  behaviourally complete" -- and not even "is defined": before the
                  table-control and key handlers were ported, 0x424260, 0x42a830
                  and 0x423440 were already cited by comments that merely mentioned
                  them. The review that set the bounds sorted definitions from
                  mentions by hand and read every function without a definition.
  engine side  -- generic engine code stands in for it (make_links, the component
                  handler, the announcement dispatcher...), listed below with why.
  uncited      -- neither. Should be empty; anything here is unported.

The census needs decomp/ (untracked, regenerated by rea decompile-all) and is
skipped with a note when it is absent.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# 0x427f10, 0x00427f10, and FUN_0042a220 -- the last is how a reimplementation says
# "this function also serves that address", for handlers the binary binds twice
# because the bodies are byte-identical. link_impls.py reads the same three forms.
ADDR_RE = re.compile(r"(?:0x0{0,2}|FUN_0{0,2})(4[0-9a-f]{5})\b")


def seeds(table):
    f = ROOT / "analysis" / f"{table}-seeds.tsv"
    rows = []
    for line in f.read_text().splitlines():
        addr, _kind, name = line.split("\t")
        rows.append((int(addr, 16), name))
    return sorted(rows)


def implemented_addrs(prefix):
    done = set()
    for f in sorted((ROOT / "src").glob(f"{prefix}_*.cpp")):
        done |= {int(m, 16) for m in ADDR_RE.findall(f.read_text())}
    return done


def decompiled(table):
    total = 0
    for d in (ROOT / "decomp").glob(f"{table}*"):
        fns = d / "functions"
        if fns.is_dir():
            total += len(list(fns.glob("*.c")))
    return total


def classified(table, threshold=0.55):
    f = ROOT / "analysis" / f"{table}-matches.txt"
    if not f.exists():
        return 0
    n = 0
    for line in f.read_text().splitlines():
        m = re.match(r"\S+\s+0x[0-9a-f]+\s+\w+\s+([0-9.]+)", line)
        if m and float(m.group(1)) >= threshold:
            n += 1
    return n


# The rules region per table, [start, end), and the decomp/ corpora that cover it.
REGIONS = {
    "dragon": (0x422A80, 0x42C290, ["dragon", "dragon_engine"]),
    "pirates": (0x422A80, 0x42DAA0, ["pirates", "pirates_rest"]),
}

# Region functions whose counterpart is generic engine code rather than a src/
# function. The same six in both binaries, at each build's own address.
ENGINE_SIDE = {
    "dragon": {
        0x422A80: "credits scroller (engine credits; QUOTE is the table key handler's)",
        0x422B50: "stops the scroller",
        0x422B80: "announcement dispatcher (engine shows Space Cadet's identical "
                  "strings; Music/Sound On/Off pause texts are not shown)",
        0x422EF0: "make_component_link -> control::make_component_link",
        0x422FE0: "make_links -> control::make_links over CurrentTable",
        0x423060: "component handler -> control::handler, ModeBeforeComponent",
    },
    "pirates": {
        0x422A90: "credits scroller (engine credits; QUOTE is the table key handler's)",
        0x422B60: "stops the scroller",
        0x422B90: "announcement dispatcher (engine shows Space Cadet's identical "
                  "strings; Music/Sound On/Off pause texts are not shown)",
        0x422F10: "make_component_link -> control::make_component_link",
        0x423000: "make_links -> control::make_links over CurrentTable",
        0x423080: "component handler -> control::handler, ModeBeforeComponent",
    },
}

# Ported, but inlined into a caller without its own address comment.
INLINED = {
    "dragon": {},
    "pirates": {0x428900: "tavern award, inlined as TavernSinkAward (pirates_part2.cpp)"},
}


def table_src_addrs(prefix):
    """Addresses cited in the table's own files only: the same address means
    different things in the two binaries."""
    files = sorted((ROOT / "src").glob(f"{prefix}_*.cpp"))
    files.append(ROOT / "src" / f"control_{prefix}.cpp")
    done = set()
    for f in files:
        if f.exists():
            done |= {int(m, 16) for m in ADDR_RE.findall(f.read_text())}
    return done


def census(table):
    lo, hi, dirs = REGIONS[table]
    fns = set()
    for d in dirs:
        fdir = ROOT / "decomp" / d / "functions"
        if not fdir.is_dir():
            continue
        for f in fdir.glob("*.c"):
            try:
                a = int(f.stem, 16)
            except ValueError:
                continue
            if lo <= a < hi:
                fns.add(a)
    print(f"  rules region 0x{lo:x}..0x{hi:x} (whole region, not just score_components[])")
    if not fns:
        print("               skipped: decomp/ not present -- run rea decompile-all first")
        return
    cited = table_src_addrs(table)
    engine = {a for a in fns if a in ENGINE_SIDE[table]}
    inlined = {a for a in fns if a in INLINED[table]}
    in_src = (fns & cited) - engine
    uncited = fns - in_src - engine - inlined
    have = len(in_src) + len(inlined) + len(engine)
    print(f"  functions    {have:>4}/{len(fns)}  "
          f"({have / len(fns) * 100:.0f}%)  with a counterpart: "
          f"{len(in_src)} cited in src/, {len(inlined)} inlined, {len(engine)} engine side")
    for a in sorted(inlined):
        print(f"               inlined     0x{a:x}  {INLINED[table][a]}")
    for a in sorted(engine):
        print(f"               engine side 0x{a:x}  {ENGINE_SIDE[table][a]}")
    if uncited:
        print(f"  UNCITED:     {', '.join(f'0x{a:x}' for a in sorted(uncited))}")


def report(table, src_prefix):
    rows = seeds(table)
    done = implemented_addrs(src_prefix)
    hit = [a for a, _n in rows if a in done]

    # A handler runs until the next seeded address; the last one gets a nominal span.
    addrs = [a for a, _n in rows]
    spans = {
        a: (addrs[i + 1] - a if i + 1 < len(addrs) else 0x200) for i, a in enumerate(addrs)
    }
    total_bytes = sum(spans.values())
    done_bytes = sum(spans[a] for a in hit)

    print(f"\n{table.upper()}")
    print(f"  decompiled   {decompiled(table):>4} functions")
    print(f"  classified   {classified(table):>4}/{len(rows)}  "
          f"({classified(table) / len(rows) * 100:.0f}%)  have a Space Cadet template")
    print(f"  implemented  {len(hit):>4}/{len(rows)}  "
          f"({len(hit) / len(rows) * 100:.0f}%)  score_components[] handlers with a C++ body")
    print(f"               {done_bytes:>4}/{total_bytes} bytes "
          f"({done_bytes / total_bytes * 100:.0f}%)")
    missing = [(a, n) for a, n in rows if a not in done]
    if missing:
        print(f"  remaining:   {', '.join(n for _a, n in missing[:8])}"
              f"{' ...' if len(missing) > 8 else ''}")
    census(table)


if __name__ == "__main__":
    targets = sys.argv[1:] or ["dragon", "pirates"]
    for t in targets:
        report(t, t)
    print("\nNOTE: every figure above is a citation count. None of it says the rules play")
    print("correctly -- nothing has been verified by a person playing in a real window.")
    print("See README.md \"Status\" for what is still open.")
    src = sorted((ROOT / "src").glob("*.cpp")) + sorted((ROOT / "src").glob("*.h"))
    hand = [f for f in src if not f.name.startswith("control_")]
    print(f"\nhand-written C++: {sum(len(f.read_text().splitlines()) for f in hand)} lines "
          f"across {len(hand)} files")
